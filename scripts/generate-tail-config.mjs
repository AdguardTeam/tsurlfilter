/**
 * Generate the minimal ESLint tail configuration for migrated rules.
 *
 * Usage: node scripts/generate-tail-config.mjs <package-dir> [output-file]
 *
 * Reads the package's effective ESLint rules, keeps exactly the fallback
 * list produced by the workspace compatibility translation (rules Oxlint
 * cannot own: type-aware without service, compiler-owned, unsupported),
 * and writes a flat ESLint config containing only those rules with their
 * original options. Every retained rule is evidence-backed: same severity,
 * same options, same file scope as the original configuration.
 */
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const packageDir = path.resolve(process.argv[2] ?? '.');
const outputFile = process.argv[3] ?? path.join(packageDir, '.eslint-tail.cjs');

const packageRequire = createRequire(path.join(packageDir, 'package.json'));
const { ESLint } = packageRequire('eslint');

const workspaceConfig = '/home/code/repos/AGCodeGuidelines-TS/AGCodeGuidelines-TS/packages/oxlint-config/dist/index.js';
const { createCompatibilityConfig } = await import(pathToFileURL(workspaceConfig).href);

// Resolve from a representative source file, not the first lint result:
// lintFiles ordering can surface config files (rollup.config.ts) whose
// option payloads differ from the source scope. Prefer src/index.ts,
// then any src sibling, so the tail carries source-scope options.
const probe = new ESLint({ cwd: packageDir });
const { readdirSync } = await import('node:fs');
const pickRepresentative = (directory) => {
    try {
        const entries = readdirSync(directory, { withFileTypes: true });
        if (entries.some((entry) => entry.isFile() && entry.name === 'index.ts')) {
            return path.join(directory, 'index.ts');
        }
        const first = entries.find((entry) => entry.isFile() && entry.name.endsWith('.ts'));
        if (first) {
            return path.join(directory, first.name);
        }
    } catch {
        // Fall through to the package-relative default below.
    }
    return undefined;
};
const representative = pickRepresentative(path.join(packageDir, 'src'))
    ?? path.join(packageDir, 'src', 'index.ts');
const reference = await probe.calculateConfigForFile(representative);

const translated = createCompatibilityConfig({
    language: 'typescript',
    rules: reference.rules,
    context: { files: ['src/**'] },
});
// Split the fallback: in-catalog type-aware rules route to the tsgolint
// service via the migrated Oxlint config (typeAware:true); only rules
// needing no type info stay in the ESLint tail, which then runs without
// a type-aware program build. Probe each fallback rule standalone: a
// parserServices error means it belongs to the service, not the tail.
const serviced = createCompatibilityConfig({
    language: 'typescript',
    typeAware: true,
    rules: reference.rules,
    context: { files: ['src/**'] },
});
const servicedSources = new Set(
    [...translated.fallback, ...serviced.fallback].length
        ? serviced.ownership
            .filter((decision) => decision.disposition === 'type-aware')
            .map((decision) => decision.source)
        : [],
);
const tail = {};
for (const entry of translated.fallback) {
    const source = entry.source ?? entry.rule;
    if (source && reference.rules[source] !== undefined && !servicedSources.has(source)) {
        tail[source] = reference.rules[source];
    }
}
const routed = [...translated.fallback]
    .map((entry) => entry.source ?? entry.rule)
    .filter((source) => servicedSources.has(source));

const content = `/** Auto-generated by scripts/generate-tail-config.mjs; do not edit. */\n`
    + `module.exports = { rules: ${JSON.stringify(tail, null, 4)} };\n`;
await writeFile(outputFile, content);
console.log(`Tail: ${Object.keys(tail).length} rules -> ${outputFile}; tsgolint: ${routed.length} [${routed.join(', ')}]`);

// Off-map: every other effective rule forced off, so the tail ESLint pass
// runs exactly the tail set over identical file selection. Merged
// overrideConfigs win over base settings, so explicit off entries stick
// for every file whose effective rules are a subset of this universe.
const offMap = {};
for (const rule of Object.keys(reference.rules ?? {})) {
    if (!(rule in tail)) {
        offMap[rule] = 'off';
    }
}
const offFile = outputFile.replace(/\.cjs$/, '.off.json');
await writeFile(offFile, `${JSON.stringify(offMap, null, 1)}\n`);
console.log(`Off-map: ${Object.keys(offMap).length} rules -> ${offFile}`);
